-- ───────────────────────── بعد التشغيل: إنشاء الحسابات ─────────────────────────
-- 1) Authentication ← Providers ← Email: عطّل Confirm email وعطّل التسجيل الذاتي (Allow new users to sign up).
-- 2) Authentication ← Users ← Add user ← Create new user، مع تفعيل Auto Confirm User:
--      admin@library.local  بكلمة مرور (6 أحرف على الأقل)
--      وفي User Metadata: {"username":"admin","full_name":"مدير النظام"}
--    (اسم الدخول في التطبيق = ما قبل @، والبريد داخلي فقط.)
-- 3) عيّن أول مدير من SQL Editor:
--      update public.profiles set role = 'admin' where username = 'admin';
