-- ───────────────────────── دوال مساعدة ─────────────────────────

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles
                 where id = auth.uid() and role = 'admin' and not disabled);
$$;

create function public.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles
                 where id = auth.uid() and role in ('librarian', 'admin') and not disabled);
$$;

create function public.log_activity(p_message text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.activity_log (user_id, username, message)
  select p.id, p.username, p_message from public.profiles p where p.id = auth.uid();
end;
$$;

-- ينشئ صف profiles تلقائياً لكل حساب جديد في Auth. الدور دائماً user.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username, full_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'full_name', '')
  );
  return new;
end;
$$;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- حماية profiles: غير المدير لا يغيّر الدور أو التعطيل. لا تعطيل بلا سبب،
-- ولا إزالة آخر مدير. عند التعطيل يُمنع الدخول في Auth أيضاً.
create function public.profiles_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare admins integer;
begin
  -- auth.uid() فارغ عند التشغيل من SQL Editor (مسموح، لتعيين أول مدير).
  if auth.uid() is not null and not public.is_admin() then
    if new.role is distinct from old.role
       or new.disabled is distinct from old.disabled
       or new.username is distinct from old.username then
      raise exception 'هذه العملية للمدير فقط';
    end if;
  end if;

  if new.disabled and not old.disabled then
    if coalesce(btrim(new.disabled_reason), '') = '' then
      raise exception 'اكتب سبب التعطيل';
    end if;
    new.disabled_at := now();
  elsif not new.disabled and old.disabled then
    new.disabled_reason := null;
    new.disabled_at := null;
  end if;

  if old.role = 'admin' and (new.role <> 'admin' or new.disabled) then
    select count(*) into admins from public.profiles
      where role = 'admin' and not disabled and id <> old.id;
    if admins < 1 then raise exception 'لا يمكن إزالة آخر مدير للنظام'; end if;
  end if;

  if new.disabled is distinct from old.disabled then
    update auth.users
       set banned_until = case when new.disabled then 'infinity'::timestamptz else null end
     where id = new.id;
  end if;
  return new;
end;
$$;
create trigger profiles_guard_trg
  before update on public.profiles
  for each row execute function public.profiles_guard();

-- ───────────────────────── دوال الاستعارة (ذرّية) ─────────────────────────

create function public.borrow_book(p_book_id integer, p_for uuid default null)
returns public.loans
language plpgsql security definer set search_path = '' as $$
declare
  me      uuid := auth.uid();
  target  uuid := coalesce(p_for, auth.uid());
  b       public.books;
  tp      public.profiles;
  l       public.loans;
begin
  if me is null then raise exception 'سجّل الدخول أولاً'; end if;
  if target <> me and not public.is_staff() then raise exception 'هذه العملية للموظفين فقط'; end if;
  select * into tp from public.profiles where id = target;
  if not found then raise exception 'المستعير غير موجود'; end if;
  if tp.disabled then raise exception 'الحساب معطّل'; end if;

  select * into b from public.books where id = p_book_id for update;
  if not found then raise exception 'الكتاب غير موجود'; end if;
  if b.is_digital then raise exception 'الكتب الرقمية تُقرأ وتُحمَّل مباشرة بلا استعارة'; end if;

  if (select count(*) from public.loans where user_id = target and returned_at is null) >= 3 then
    raise exception 'وصلت إلى الحد الأقصى: 3 كتب';
  end if;
  if exists (select 1 from public.loans
             where user_id = target and book_id = p_book_id and returned_at is null) then
    raise exception 'هذا الكتاب مستعار بالفعل';
  end if;
  if b.available_copies <= 0 then raise exception 'لا توجد نسخة متاحة الآن، يمكنك حجزه'; end if;

  update public.books set available_copies = available_copies - 1 where id = p_book_id;
  delete from public.reservations where book_id = p_book_id and user_id = target;
  insert into public.loans (book_id, user_id, due_at)
    values (p_book_id, target, now() + interval '14 days')
    returning * into l;
  perform public.log_activity('استعارة كتاب: ' || b.title || ' (' || tp.username || ')');
  return l;
end;
$$;

create function public.return_loan(p_loan_id integer) returns void
language plpgsql security definer set search_path = '' as $$
declare l public.loans; b public.books; first_user uuid;
begin
  if not public.is_staff() then raise exception 'هذه العملية للموظفين فقط'; end if;
  select * into l from public.loans where id = p_loan_id for update;
  if not found then raise exception 'الاستعارة غير موجودة'; end if;
  if l.returned_at is not null then raise exception 'تم إرجاع هذا الكتاب مسبقاً'; end if;

  select * into b from public.books where id = l.book_id for update;
  update public.loans set returned_at = now() where id = p_loan_id;
  update public.books set available_copies = least(total_copies, available_copies + 1) where id = b.id;

  -- إشعار أول المنتظرين في الحجز.
  select user_id into first_user from public.reservations
    where book_id = b.id order by created_at limit 1;
  if first_user is not null then
    insert into public.notifications (user_id, title, subtitle, dedupe_key)
      values (first_user, 'الكتاب الذي حجزته أصبح متاحاً', b.title, 'resv-' || b.id || '-' || p_loan_id)
      on conflict do nothing;
  end if;
  perform public.log_activity('إرجاع كتاب: ' || b.title);
end;
$$;

create function public.extend_loan(p_loan_id integer) returns void
language plpgsql security definer set search_path = '' as $$
declare l public.loans;
begin
  if not public.is_staff() then raise exception 'هذه العملية للموظفين فقط'; end if;
  select * into l from public.loans where id = p_loan_id for update;
  if not found then raise exception 'الاستعارة غير موجودة'; end if;
  if l.returned_at is not null then raise exception 'لا يمكن تمديد كتاب تم إرجاعه'; end if;
  update public.loans set due_at = due_at + interval '7 days' where id = p_loan_id;
  perform public.log_activity('تمديد موعد استعارة رقم ' || p_loan_id);
end;
$$;

create function public.reserve_book(p_book_id integer) returns void
language plpgsql security definer set search_path = '' as $$
declare b public.books;
begin
  if auth.uid() is null then raise exception 'سجّل الدخول أولاً'; end if;
  select * into b from public.books where id = p_book_id;
  if not found then raise exception 'الكتاب غير موجود'; end if;
  if b.is_digital or b.available_copies > 0 then
    raise exception 'الكتاب متاح الآن، يمكنك استعارته مباشرة';
  end if;
  insert into public.reservations (book_id, user_id) values (p_book_id, auth.uid())
    on conflict do nothing;
end;
$$;

revoke all on function public.borrow_book(integer, uuid), public.return_loan(integer),
  public.extend_loan(integer), public.reserve_book(integer), public.log_activity(text)
  from public, anon;
grant execute on function public.borrow_book(integer, uuid), public.return_loan(integer),
  public.extend_loan(integer), public.reserve_book(integer), public.log_activity(text)
  to authenticated;

