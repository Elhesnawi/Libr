-- المكتبة الذكية: مخطط قاعدة البيانات (Supabase / PostgreSQL)
-- يُشغَّل مرة واحدة في: Supabase ← SQL Editor ← New query ← Run.
-- ينشئ: الجداول، صلاحيات الأمان (RLS)، دوال الاستعارة والإرجاع، التخزين، والبيانات الأولية.
-- لا يُنشئ الحسابات: الحسابات تُنشأ من Authentication ← Users (راجع آخر الملف).

-- ───────────────────────── الأنواع ─────────────────────────
create type public.user_role      as enum ('user', 'librarian', 'admin');
create type public.org_kind       as enum ('general', 'branch', 'office');
create type public.request_status as enum ('pending', 'accepted', 'rejected');

-- ───────────────────────── الجداول ─────────────────────────

-- المستخدمون. كلمات المرور في نظام Supabase Auth (مشفّرة) وليست هنا.
create table public.profiles (
  id              uuid primary key references auth.users (id) on delete cascade,
  username        text not null unique check (username ~ '^[A-Za-z0-9_.-]{3,30}$'),
  full_name       text not null default '',
  role            public.user_role not null default 'user',
  org_kind        public.org_kind,
  org_values      text[] not null default '{}',
  phone           text not null default '' check (phone = '' or phone ~ '^[0-9]{9,15}$'),
  disabled        boolean not null default false,
  disabled_reason text,
  disabled_at     timestamptz,
  last_login      timestamptz,
  created_at      timestamptz not null default now()
);

create table public.categories (
  id       integer generated by default as identity primary key,
  name     text not null unique,
  icon_key text not null default 'folder'
);

create table public.books (
  id               integer generated by default as identity primary key,
  title            text not null,
  author           text not null,
  category_id      integer not null references public.categories (id),
  is_digital       boolean not null default false,
  total_copies     integer not null default 1 check (total_copies >= 0),
  available_copies integer not null default 1 check (available_copies >= 0),
  publish_date     date,
  pages            integer not null default 12,
  cover_path       text,   -- مسار في bucket: covers
  file_path        text,   -- مسار PDF في bucket: book-files (للكتب الرقمية)
  created_at       timestamptz not null default now(),
  check (available_copies <= total_copies)
);
create index books_category_idx on public.books (category_id);

create table public.loans (
  id          integer generated by default as identity primary key,
  book_id     integer not null references public.books (id),
  user_id     uuid    not null references public.profiles (id),
  borrowed_at timestamptz not null default now(),
  due_at      timestamptz not null,
  returned_at timestamptz            -- فارغ = استعارة نشطة
);
create index loans_user_idx on public.loans (user_id);
create unique index loans_one_active_per_book on public.loans (book_id, user_id) where returned_at is null;

create table public.favorites (
  user_id uuid not null references public.profiles (id) on delete cascade,
  book_id integer not null references public.books (id) on delete cascade,
  primary key (user_id, book_id)
);

create table public.reservations (
  book_id    integer not null references public.books (id) on delete cascade,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),  -- ترتيب الطابور
  primary key (book_id, user_id)
);

create table public.ratings (
  id         integer generated by default as identity primary key,
  book_id    integer not null references public.books (id) on delete cascade,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  stars      integer not null check (stars between 1 and 5),
  comment    text not null default '',
  created_at timestamptz not null default now(),
  unique (book_id, user_id)
);

create table public.reading_progress (
  user_id uuid not null references public.profiles (id) on delete cascade,
  book_id integer not null references public.books (id) on delete cascade,
  page    integer not null default 1,
  primary key (user_id, book_id)
);

create table public.downloads (
  user_id uuid not null references public.profiles (id) on delete cascade,
  book_id integer not null references public.books (id) on delete cascade,
  primary key (user_id, book_id)
);

create table public.book_requests (
  id         integer generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  title      text not null,
  author     text not null default '',
  status     public.request_status not null default 'pending',
  created_at timestamptz not null default now()
);

create table public.notifications (
  id         integer generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  title      text not null,
  subtitle   text not null default '',
  read       boolean not null default false,
  dedupe_key text,
  created_at timestamptz not null default now(),
  unique (user_id, dedupe_key)
);
create index notifications_user_idx on public.notifications (user_id, created_at desc);

create table public.announcements (
  id         integer generated by default as identity primary key,
  body       text not null,
  created_at timestamptz not null default now()
);

create table public.activity_log (
  id       integer generated by default as identity primary key,
  user_id  uuid references public.profiles (id) on delete set null,
  username text not null default 'system',
  message  text not null,
  at       timestamptz not null default now()
);
create index activity_log_at_idx on public.activity_log (at desc);

